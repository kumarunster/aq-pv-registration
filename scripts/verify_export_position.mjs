import puppeteer from 'puppeteer-core';
const CHROME = '/home/moltbot/.cache/puppeteer/chrome/linux-146.0.7680.76/chrome-linux64/chrome';
const BASE = 'http://localhost:8092';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(BASE + '/admin/login', { waitUntil: 'networkidle0' });
await page.type('input[type="email"]', 'admin@amelanq.com');
await page.type('input[type="password"]', 'Admin1234!');
await page.click('button[type="submit"]');
await new Promise(r => setTimeout(r, 3000));
await page.goto(BASE + '/admin/kunden', { waitUntil: 'domcontentloaded' });
await new Promise(r => setTimeout(r, 1500));
await page.evaluate(() => {
  const inp = document.querySelector('input[type="search"]');
  inp.value = 'E2E';
  inp.dispatchEvent(new Event('input', { bubbles: true }));
});
await new Promise(r => setTimeout(r, 2000));
await page.evaluate(() => {
  const rows = [...document.querySelectorAll('div.cursor-pointer')].filter(r => r.textContent.includes('E2E'));
  if (rows.length) rows[rows.length - 1].click();
});
await new Promise(r => setTimeout(r, 1500));
const order = await page.evaluate(() => [...document.querySelectorAll('#customer-form button')].map(b => b.id || b.textContent.trim().slice(0,15)).filter(Boolean));
console.log('Button-Reihenfolge:', JSON.stringify(order));
const idx = (id) => order.findIndex(x => x.includes(id));
const ok = idx('customer-export-json') > idx('customer-form-save');
console.log(ok ? 'Export RECHTS von Speichern: PASS ✅' : 'Export NICHT rechts: FAIL ❌');
await browser.close();
process.exit(ok ? 0 : 1);
