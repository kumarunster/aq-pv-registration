import puppeteer from 'puppeteer'
const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const page = await browser.newPage()
page.on('console', (m) => console.log('CONSOLE[' + m.type() + ']:', m.text().slice(0, 200)))
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
page.on('response', (r) => { if (r.url().includes('/assets/') || r.url().includes('installer')) console.log('RESP', r.status(), r.url()) })
await page.goto('http://localhost:8092/installer/login', { waitUntil: 'domcontentloaded', timeout: 30000 })
await new Promise(r => setTimeout(r, 8000))
console.log('URL:', page.url())
const body = await page.evaluate(() => document.body ? document.body.innerText.slice(0, 400) : '(kein body)')
console.log('BODY:', body)
const app = await page.evaluate(() => document.getElementById('app') ? document.getElementById('app').innerHTML.slice(0, 400) : '(kein #app)')
console.log('#APP:', app)
await page.screenshot({ path: 'scripts/flow-debug3.png' })
await browser.close()
